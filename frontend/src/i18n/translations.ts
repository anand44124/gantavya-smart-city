// Badge translation helper
export function translateBadge(badgeLevel: string, t: (key: string, defaultText?: string) => string): string {
  if (badgeLevel.includes('Bronze') || badgeLevel.includes('Scout')) return t('badge_bronze', 'Bronze Scout')
  if (badgeLevel.includes('Silver') || badgeLevel.includes('Vigilante')) return t('badge_silver', 'Silver Vigilante')
  if (badgeLevel.includes('Gold') || badgeLevel.includes('Champion')) return t('badge_gold', 'Gold Civic Champion')
  if (badgeLevel.includes('Platinum') || badgeLevel.includes('Guardian')) return t('badge_platinum', 'Platinum City Guardian')
  if (badgeLevel.includes('Diamond') || badgeLevel.includes('Reformer')) return t('badge_diamond', 'Diamond Reformer')
  return badgeLevel
}
